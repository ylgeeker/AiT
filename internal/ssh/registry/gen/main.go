// Command gen regenerates internal/ssh/registry/all/imports.go from top-level register.go packages.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	copyrightHeader = `/**
 * Copyright 2026 AiT authors.
 *
 * Licensed under the Apache License, Version 2.0 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     http://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
**/

`
)

func main() {
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}

	toolDir := filepath.Join(root, "internal", "ssh")
	entries, err := os.ReadDir(toolDir)
	if err != nil {
		fatal(err)
	}

	var pkgs []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		reg := filepath.Join(toolDir, e.Name(), "register.go")
		if _, err := os.Stat(reg); err != nil {
			continue
		}
		pkgs = append(pkgs, e.Name())
	}
	sort.Strings(pkgs)

	var body strings.Builder
	body.WriteString(copyrightHeader)
	body.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	body.WriteString("// Package all blank-imports every top-level command registrar (breaks import cycles with cli).\n")
	body.WriteString("package all\n\nimport (\n")
	for _, name := range pkgs {
		fmt.Fprintf(&body, "\t_ \"github.com/os-artificer/AiT/internal/ssh/%s\"\n", name)
	}
	body.WriteString(")\n")

	formatted, err := format.Source([]byte(body.String()))
	if err != nil {
		fatal(fmt.Errorf("format: %w", err))
	}

	outPath := filepath.Join(root, "internal", "ssh", "registry", "all", "imports.go")
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d imports)\n", outPath, len(pkgs))
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from %s", dir)
		}
		dir = parent
	}
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "registry/gen: %v\n", err)
	os.Exit(1)
}

// silence unused import when formatting empty buffer edge cases
var _ = bytes.Buffer{}
